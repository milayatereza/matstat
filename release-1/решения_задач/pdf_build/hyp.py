def t1(d):
    d.head("Задача 1")
    d.line("Дано: n = 15;  s² = 21,9;  α = 0,01;  H₀: D(X) = 20;  H₁: D(X) > 20.")
    d.line("Решение.")
    d.para("Генеральная совокупность нормальна, исправленную выборочную дисперсию сравниваем с гипотетической σ₀² = 20, поэтому применяем критерий χ². Так как H₁: D(X) > 20, критическая область правосторонняя: χ²набл > χ²крит.",indent=4,hang=5)
    d.para("Шаг 1. Число степеней свободы: k = n − 1 = 15 − 1 = 14.",indent=4,hang=5)
    d.para("Шаг 2. Критическая точка по таблице χ²-распределения для α = 0,01 и k = 14: χ²крит(0,01; 14) = 29,14.",indent=4,hang=5)
    d.para("Шаг 3. Наблюдаемое значение критерия χ²набл = (n − 1)s² / σ₀²:",indent=4,hang=5)
    d.line("χ²набл = [[14 · 21,9||20]] = [[306,6||20]] = 15,33     (14 · 21,9 = 306,6).",indent=10)
    d.para("Шаг 4. Сравниваем: χ²набл = 15,33 < χ²крит = 29,14, то есть значение не попало в критическую область.",indent=4,hang=5)
    d.para("Вывод: при α = 0,01 нет оснований отвергать H₀. Данные согласуются с тем, что D(X) = 20.")
    d.gap(.8)

