    d.gap(.3)
    d.para("Порядок проверки гипотезы (лекция 6): 1) формулируем H₀ и H₁; 2) задан уровень значимости α; 3) выбираем критерий и по таблице находим критическую точку; 4) по выборке вычисляем наблюдаемое значение критерия; 5) сравниваем и делаем вывод: если наблюдаемое значение попало в критическую область, H₀ отвергаем, иначе нет оснований её отвергать (это не доказывает, что H₀ верна).")
