def F(x,nd): return f"{x:.{nd}f}".replace(".",",").replace("-","−")
def table(d,header,rows,widths,fs=10):
    x0=LM+4*mm; xs=[x0]
    for w in widths: xs.append(xs[-1]+w*mm)
    def row(r):
        d.need(2); y=d.y; top=y+ROW*0.72; bot=y-ROW*0.28
        c=d.c; c.setLineWidth(.5)
        c.line(xs[0],top,xs[-1],top); c.line(xs[0],bot,xs[-1],bot)
        for xx in xs: c.line(xx,top,xx,bot)
        for i,t in enumerate(r):
            w=lw(t,fs); draw_line(c,xs[i]+(xs[i+1]-xs[i]-w)/2,y,t,fs)
        d.y-=ROW
    d.need(len(rows)+2); row(header)
    for r in rows: row(r)
    d.gap(.3)

