def t7(d):
    n=[12,15,18,20]; s2=[.27,.52,.85,.99]; k=[x-1 for x in n]; K=sum(k)
    d.head("Задача 7")
    d.line("Дано: l = 4;  n = 12, 15, 18, 20;  s² = 0,27; 0,52; 0,85; 0,99;  α = 0,01;  H₀: D(X) = D(Y) = D(Z) = D(U).")
    d.line("Решение.")
    d.para("Сравниваем несколько дисперсий при разных объёмах выборок, применяем критерий Бартлетта: Bнабл = V / C. Если Bнабл > χ²крит(α; l − 1), H₀ отвергаем.",indent=4,hang=5)
    d.para("Шаг 1. Критическая точка: число степеней свободы l − 1 = 4 − 1 = 3, по таблице χ² для α = 0,01: χ²крит(0,01; 3) = 11,34.",indent=4,hang=5)
    d.para("Шаг 2. Степени свободы kᵢ = nᵢ − 1 и суммарное k:",indent=4,hang=5)
    d.line("k₁ = 11,  k₂ = 14,  k₃ = 17,  k₄ = 19;     k = 11 + 14 + 17 + 19 = 61.",indent=10)
    d.para("Шаг 3. Заполняем вспомогательную таблицу (десятичные логарифмы берём с 5 знаками):",indent=4,hang=5)
    lgs=[round(math.log10(x),5) for x in s2]
    rows=[]; sk=0; slg=0; sinv=0
    for i in range(4):
        ks=round(k[i]*s2[i],4); kl=round(k[i]*lgs[i],5); sk+=ks; slg+=kl; sinv+=1/k[i]
        rows.append([str(i+1),str(n[i]),str(k[i]),F(s2[i],2),F(ks,4),F(lgs[i],5),F(kl,5),F(1/k[i],4)])
    rows.append(["Σ","","61","",F(sk,4),"",F(slg,5),F(sinv,4)])
    table(d,["i","nᵢ","kᵢ","sᵢ²","kᵢsᵢ²","lg sᵢ²","kᵢ·lg sᵢ²","1/kᵢ"],rows,[10,14,14,18,24,26,30,24])
    sb=sk/K; lsb=round(math.log10(round(sb,5)),5)
    d.para("Шаг 4. Взвешенная средняя дисперсия s̄² = Σkᵢsᵢ² / k:",indent=4,hang=5)
    d.line(f"s̄² = [[{F(sk,4)}||61]] = {F(sb,5)};     lg s̄² = {F(lsb,5)}.",indent=10)
    d.para("Шаг 5. Показатель V = 2,303·( k·lg s̄² − Σkᵢ·lg sᵢ² ):",indent=4,hang=5)
    a=round(61*lsb,5); diff=a-slg; V=2.303*diff
    d.line(f"k·lg s̄² = 61 · ({F(lsb,5)}) = {F(a,5)};",indent=10)
    d.line(f"{F(a,5)} − ({F(slg,5)}) = {F(diff,5)};",indent=10)
    d.line(f"V = 2,303 · {F(diff,5)} = {F(V,3)}.",indent=10)
    d.para("Шаг 6. Поправка C = 1 + [ Σ(1/kᵢ) − 1/k ] / (3·(l − 1)):",indent=4,hang=5)
    inv=round(1/61,4); sinv4=round(sinv,4); C=1+(sinv4-inv)/9
    d.line(f"C = 1 + [[{F(sinv4,4)} − {F(inv,4)}||3 · 3]] = 1 + [[{F(sinv4-inv,4)}||9]] = {F(C,4)}.",indent=10)
    d.para("Шаг 7. Наблюдаемое значение:",indent=4,hang=5)
    B=V/C
    d.line(f"Bнабл = [[V||C]] = [[{F(V,3)}||{F(C,4)}]] ≈ {F(B,2)}.",indent=10)
    d.para(f"Шаг 8. Сравниваем: Bнабл = {F(B,2)} < χ²крит = 11,34, значение не попало в критическую область.",indent=4,hang=5)
    d.para(f"Вывод: при α = 0,01 гипотеза H₀ принимается (нет оснований её отвергать): дисперсии можно считать однородными. Общая оценка дисперсии s̄² ≈ {F(sb,3)}.")
    d.gap(.8)
    return B

