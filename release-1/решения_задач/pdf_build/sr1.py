def img(d,path,wmm,hmm):
    d.need(int(hmm/6.6)+2); d.c.drawImage(path,LM+8*mm,d.y-hmm*mm+ROW*.5,width=wmm*mm,height=hmm*mm); d.y-=hmm*mm+ROW*.3

def table(d,header,rows,widths,fs=10.5):
    x0=LM+8*mm; xs_=[x0]
    for w in widths: xs_.append(xs_[-1]+w*mm)
    def row(r):
        d.need(2); y=d.y; top=y+ROW*0.72; bot=y-ROW*0.28; c=d.c; c.setLineWidth(.5)
        c.line(xs_[0],top,xs_[-1],top); c.line(xs_[0],bot,xs_[-1],bot)
        for xx in xs_: c.line(xx,top,xx,bot)
        for i,t in enumerate(r):
            w=lw(t,fs); draw_line(c,xs_[i]+(xs_[i+1]-xs_[i]-w)/2,y,t,fs)
        d.y-=ROW
    d.need(len(rows)+2); row(header)
    for r in rows: row(r)
    d.gap(.3)

