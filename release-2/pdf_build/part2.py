from render import *
import json
def f(x,nd=1): return f"{x:.{nd}f}".replace(".",",")
def build(d):
    D=json.load(open("data.json"))
    d.head("Часть 2. Практические задачи")
    d.para("Метод (лекция 4): нормальная генеральная совокупность, σ известно. Доверительный интервал для математического ожидания a:",indent=0)
    d.line("~x − ε < a < ~x + ε,    ε = [[t·σ₀||@{n}]],    Φ(t) = [[γ||2]]",indent=6)
    d.para("где ~x — выборочная средняя, Φ(t) — функция Лапласа (значение t берём из таблицы).",indent=0)
    d.gap(.5)
    # ---- Задача 1
    d.head("Задача 1")
    d.line("Дано: n = 16,  σ² = 0,0016,  γ = 0,95.  Найти доверительный интервал для a.")
    d.line("Решение.")
    d.line("1) Среднее квадратическое отклонение: σ₀ = @{0,0016} = 0,04.",indent=4)
    d.line("2) Выборочная средняя. Складываем значения по 4 штуки:",indent=4)
    v=[1.38,1.41,1.33,1.45,1.42,1.46,1.43,1.41,1.36,1.31,1.41,1.48,1.44,1.36,1.38,1.40]
    ss=[]
    for i in range(0,16,4):
        g=v[i:i+4]; ss.append(sum(g))
        d.line(" + ".join(f(x,2) for x in g)+" = "+f(sum(g),2),indent=10)
    d.line("Σx = "+" + ".join(f(s,2) for s in ss)+" = "+f(sum(ss),2),indent=10)
    d.line("~x = [[Σx||n]] = [[22,43||16]] = 1,401875",indent=10)
    d.line("3) Из условия Φ(t) = [[γ||2]] = [[0,95||2]] = 0,475",indent=4)
    d.line("по таблице функции Лапласа находим t = 1,96.",indent=9)
    d.line("4) Точность оценки:",indent=4)
    d.line("ε = [[t·σ₀||@{n}]] = [[1,96·0,04||@{16}]] = [[0,0784||4]] = 0,0196",indent=10)
    d.line("5) Доверительный интервал:",indent=4)
    d.line("1,401875 − 0,0196 < a < 1,401875 + 0,0196",indent=10)
    d.line("1,382275 < a < 1,421475",indent=10)
    d.line("Ответ: a ∈ (1,382275; 1,421475) с надёжностью γ = 0,95.")
    d.gap(.6)
    # ---- Задача 2 и 3
    def task(num,title,rows,s,total,xb,eps,lo,hi,sq):
        d.head(f"Задача {num}")
        d.line(f"Дано: n = 100,  s = {s}  (σ₀ = {s}),  γ = 0,95.")
        d.line("Решение.")
        d.line("1) Выборочная средняя. Сумма значений по строкам таблицы:",indent=4)
        tot=[]
        for i,r in enumerate(rows):
            tot.append(sum(r)); d.line(f"строка {i+1}:  Σ = {f(sum(r))}",indent=10)
        d.line("Σx = "+" + ".join(f(x) for x in tot)+" = "+f(sum(tot)),indent=10)
        d.line(f"~x = [[Σx||n]] = [[{f(sum(tot))}||100]] = {xb}",indent=10)
        d.line("2) Φ(t) = [[γ||2]] = [[0,95||2]] = 0,475, по таблице Лапласа t = 1,96.",indent=4)
        d.line("3) Точность оценки:",indent=4)
        d.line(f"ε = [[t·σ₀||@{{n}}]] = [[1,96·{s}||@{{100}}]] = [[{sq}||10]] = {eps}",indent=10)
        d.line("4) Доверительный интервал:",indent=4)
        d.line(f"{xb} − {eps} < a < {xb} + {eps}",indent=10)
        d.line(f"{lo} < a < {hi}",indent=10)
        d.line(f"Ответ: ~x = {xb};  a ∈ ({lo}; {hi}) с надёжностью γ = 0,95.")
        d.gap(.6)
    task(2,"",D["r2"],6,0,"4,941","1,176","3,765","6,117","11,76")
    task(3,"",D["r3"],5,0,"37,592","0,98","36,612","38,572","9,8")
