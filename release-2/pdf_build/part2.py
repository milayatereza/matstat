def f(x,nd=1): return f"{x:.{nd}f}".replace(".",",")
def term(x,nd): 
    t=f(x,nd); return f"({t.replace('-','−')})" if x<0 else t
def sumline(d,vals,nd,indent):
    d.para(" + ".join(term(x,nd) for x in vals)+" = "+f(sum(vals),nd).replace("-","−"),indent=indent,hang=6)

def intro(d):
    d.head("Часть 2. Практические задачи")
    d.para("Во всех задачах выборка взята из нормальной генеральной совокупности, СКО известно, поэтому доверительный интервал для математического ожидания a строим по формулам лекции 4 (повторный отбор):")
    d.line("~x − ε < a < ~x + ε,        ε = [[t·σ₀||@{n}]],        Φ(t) = [[γ||2]],",indent=6)
    d.line("где ~x = [[Σxᵢ||n]] — выборочная средняя,",indent=6)
    d.line("σ₀ — известное СКО, γ — доверительная вероятность,",indent=6)
    d.line("Φ(t) — функция Лапласа, значение t находим по её таблице.",indent=6)
    d.gap(.6)

def task1(d):
    d.head("Задача 1")
    d.line("Дано: n = 16;  σ² = 0,0016;  γ = 0,95;  распределение нормальное.")
    d.line("Найти: доверительный интервал для a.")
    d.gap(.3)
    d.line("Решение.")
    d.para("Шаг 1. Находим СКО. По условию известна дисперсия, а в формуле ε нужно σ₀:",indent=4,hang=5)
    d.line("σ₀ = @{σ²} = @{0,0016} = 0,04     (проверка: 0,04² = 0,0016).",indent=10)
    d.para("Шаг 2. Находим выборочную среднюю ~x = Σxᵢ / n. Чтобы не ошибиться в сложении, суммируем по четыре числа:",indent=4,hang=5)
    v=[1.38,1.41,1.33,1.45,1.42,1.46,1.43,1.41,1.36,1.31,1.41,1.48,1.44,1.36,1.38,1.40]
    ss=[]
    for i in range(0,16,4):
        g=v[i:i+4]; ss.append(sum(g)); sumline(d,g,2,10)
    d.line("Σxᵢ = "+" + ".join(f(s,2) for s in ss)+" = "+f(sum(ss),2),indent=10)
    d.line("~x = [[Σxᵢ||n]] = [[22,43||16]] = 1,401875",indent=10)
    d.para("Шаг 3. Находим t. Из формулы Φ(t) = γ/2 подставляем γ = 0,95:",indent=4,hang=5)
    d.line("Φ(t) = [[0,95||2]] = 0,475.",indent=10)
    d.para("В таблице функции Лапласа ищем значение 0,475: оно стоит в строке 1,9 и столбце 0,06, значит t = 1,96.",indent=10,hang=0)
    d.para("Шаг 4. Находим точность оценки ε. Подставляем в формулу ε = t·σ₀/@{n}:",indent=4,hang=5)
    d.line("ε = [[1,96 · 0,04||@{16}]]",indent=10)
    d.para("числитель: 1,96 · 0,04 = 0,0784   (196 · 4 = 784, сдвигаем запятую на 4 знака);",indent=10)
    d.line("знаменатель: @{16} = 4;",indent=10)
    d.line("ε = [[0,0784||4]] = 0,0196.",indent=10)
    d.para("Шаг 5. Записываем доверительный интервал ~x − ε < a < ~x + ε и считаем границы:",indent=4,hang=5)
    d.line("нижняя граница: 1,401875 − 0,0196 = 1,382275;",indent=10)
    d.line("верхняя граница: 1,401875 + 0,0196 = 1,421475.",indent=10)
    d.line("1,382275 < a < 1,421475.",indent=10)
    d.para("Ответ: с надёжностью 0,95 истинное математическое ожидание a ∈ (1,382275; 1,421475).")
    d.gap(.8)

def task23(d,num,rows,s,xb,prod,eps,lo,hi):
    d.head(f"Задача {num}")
    d.line(f"Дано: n = 100;  s = {s};  γ = 0,95;  распределение нормальное.")
    d.line("Найти: 1) выборочное среднее ~x;  2) доверительный интервал для a.")
    d.para(f"Так как СКО известно, берём σ₀ = s = {s}.")
    d.gap(.3)
    d.line("Решение.")
    d.para("Шаг 1. Выборочная средняя ~x = Σxᵢ / n. Складываем значения выборки по строкам таблицы из условия (сначала сумма каждой строки):",indent=4,hang=5)
    tot=[]
    for i,r in enumerate(rows):
        tot.append(sum(r)); d.line(f"строка {i+1}:",indent=10)
        sumline(d,r,1,14)
    d.line("Складываем суммы строк:",indent=10)
    d.para("Σxᵢ = "+" + ".join(f(x) for x in tot)+" = "+f(sum(tot)),indent=14,hang=6)
    d.line(f"~x = [[Σxᵢ||n]] = [[{f(sum(tot))}||100]] = {xb}",indent=10)
    d.para("Шаг 2. Находим t из условия Φ(t) = γ/2:",indent=4,hang=5)
    d.line("Φ(t) = [[0,95||2]] = 0,475,   по таблице функции Лапласа t = 1,96.",indent=10)
    d.para("Шаг 3. Находим точность оценки ε = t·σ₀/@{n}:",indent=4,hang=5)
    d.line(f"ε = [[1,96 · {s}||@{{100}}]]",indent=10)
    d.line(f"числитель: 1,96 · {s} = {prod};      знаменатель: @{{100}} = 10;",indent=10)
    d.line(f"ε = [[{prod}||10]] = {eps}.",indent=10)
    d.para("Шаг 4. Строим интервал ~x − ε < a < ~x + ε:",indent=4,hang=5)
    d.line(f"нижняя граница: {xb} − {eps} = {lo};",indent=10)
    d.line(f"верхняя граница: {xb} + {eps} = {hi}.",indent=10)
    d.line(f"{lo} < a < {hi}.",indent=10)
    d.para(f"Ответ: ~x = {xb};  a ∈ ({lo}; {hi}) с надёжностью 0,95.")
    d.gap(.8)

