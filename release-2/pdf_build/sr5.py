def student_raw(d,num,cond,v,g,tval,gtxt,qs_dec=4,unit="",nd_d=4):
    n=len(v); S=sum(v); xb=S/n
    d.head(f"Задача {num}")
    d.line("Дано: "+cond)
    d.line("Найти: 1) выборочное среднее ~x;  2) доверительный интервал для a.")
    d.line("Решение.")
    d.para("Шаг 1. Выборочная средняя. Складываем все значения выборки:",indent=4,hang=5)
    # sums in groups of 6
    grp=[v[i:i+6] for i in range(0,n,6)]
    nd=2 if num==1 else 1
    for gg in grp:
        d.para(" + ".join(term(x,nd) for x in gg)+" = "+F(sum(gg),nd),indent=10,hang=6)
    d.line("Σxᵢ = "+" + ".join(F(sum(gg),nd) for gg in grp)+" = "+F(S,nd),indent=10)
    xbr=round(xb,5)
    xs=F(xb,5) if abs(xb-round(xb,4))>1e-9 else F(xb,4)
    xbv=float(xs.replace(",",".").replace("−","-"))
    d.line(f"~x = [[Σxᵢ||n]] = [[{F(S,nd)}||{n}]] = {xs}",indent=10)
    d.para("Шаг 2. Исправленная дисперсия s². Для каждого значения считаем отклонение xᵢ − ~x и его квадрат:",indent=4,hang=5)
    rows=[];ss=0
    dd=[]
    for i,x in enumerate(v,1):
        dv=round(x-xbv,5 if num!=1 else 4); sq=round(dv*dv,8 if num==1 else qs_dec); ss+=sq; dd.append((x,dv,sq))
        rows.append([str(i),F(x,nd),F(dv,5 if num!=1 else 4),F(sq,8 if num==1 else qs_dec)])
    table(d,["i","xᵢ","xᵢ − ~x","(xᵢ − ~x)²"],rows,[14,30,36,40])
    qd=8 if num==1 else qs_dec
    d.line(f"Σ(xᵢ − ~x)² = {F(ss,qd)}",indent=10)
    s2=ss/(n-1); s2d=7 if num==1 else 4
    d.line(f"s² = [[Σ(xᵢ − ~x)²||n − 1]] = [[{F(ss,qd)}||{n-1}]] = {F(s2,s2d)}",indent=10)
    s=math.sqrt(s2); sd=5 if num==1 else 4
    d.line(f"s = @{{{F(s2,s2d)}}} = {F(round(s,sd),sd)}",indent=10)
    d.para(f"Шаг 3. Находим tγ по таблице Стьюдента: γ = {gtxt}, n = {n} (k = n − 1 = {n-1}), tγ = {F(tval,3)}.",indent=4,hang=5)
    sq_n=round(math.sqrt(n),4)
    d.para("Шаг 4. Точность оценки ε = tγ·s/@{n}. Подставляем:",indent=4,hang=5)
    sr=round(s,sd)
    prod=tval*sr
    d.line(f"ε = [[{F(tval,3)} · {F(sr,sd)}||@{{{n}}}]]",indent=10)
    d.line(f"числитель: {F(tval,3)} · {F(sr,sd)} = {F(prod,5)};     знаменатель: @{{{n}}} = {F(sq_n,4)};",indent=10)
    eps=prod/sq_n; ed=4 if num==1 else 3
    epsr=round(eps,ed)
    d.line(f"ε = [[{F(prod,5)}||{F(sq_n,4)}]] = {F(epsr,ed)}.",indent=10)
    xd=4 if num==1 else 3
    lo=round(xbv-epsr,xd); hi=round(xbv+epsr,xd)
    d.para("Шаг 5. Границы интервала ~x − ε < a < ~x + ε:",indent=4,hang=5)
    d.line(f"нижняя граница: {xs} − {F(epsr,ed)} = {F(lo,xd)};",indent=10)
    d.line(f"верхняя граница: {xs} + {F(epsr,ed)} = {F(hi,xd)}.",indent=10)
    d.line(f"{F(lo,xd)} < a < {F(hi,xd)}.",indent=10)
    d.para(f"Ответ: ~x = {F(xbv,xd)};  с надёжностью {gtxt} a ∈ ({F(lo,xd)}; {F(hi,xd)}).")
    d.gap(.8)
    return xbv,lo,hi

def term(x,nd):
    t=F(x,nd); return f"({t})" if x<0 else t

