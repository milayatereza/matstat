    d.line("Решение. Ряд дискретный, σ неизвестно, n мало, значит используем распределение Стьюдента.")
    d.para(f"Шаг 1. Объём выборки: n = Σmⱼ = 8 + 4 + 2 + 3 + 5 = {n}.",indent=4,hang=5)
    d.para("Шаг 2. Оценка измеряемой величины — выборочная средняя ~x = Σ mⱼxⱼ / n:",indent=4,hang=5)
    d.line("Σ mⱼxⱼ = 8·110 + 4·111 + 2·112 + 3·113 + 5·114 = 880 + 444 + 224 + 339 + 570 = 2457,",indent=10) if False else None
    d.para("Σ mⱼxⱼ = 8·110 + 4·111 + 2·112 + 3·113 + 5·114 = 880 + 444 + 224 + 339 + 570 = 2457,",indent=10,hang=0)
    S=sum(a*b for a,b in zip(xs,m)); xb=round(S/n,4)
    d.line(f"~x = [[2457||22]] = {F(xb,4)} м.",indent=10)
    d.para("Шаг 3. Исправленная дисперсия s² = Σ mⱼ(xⱼ − ~x)² / (n − 1). Считаем в таблице:",indent=4,hang=5)
    rows=[];tot=0
    for x,mm in zip(xs,m):
        dv=round(x-xb,4); sq=round(dv*dv,4); p=round(mm*sq,4); tot+=p
        rows.append([str(x),str(mm),F(dv,4),F(sq,4),F(p,4)])
    table(d,["xⱼ","mⱼ","xⱼ − ~x","(xⱼ − ~x)²","mⱼ(xⱼ − ~x)²"],rows,[18,14,30,32,38])
    d.line(f"Σ mⱼ(xⱼ − ~x)² = {F(tot,4)}",indent=10)
    s2=tot/(n-1)
    d.line(f"s² = [[{F(tot,4)}||{n-1}]] = {F(s2,4)}",indent=10)
    s=round(math.sqrt(s2),4)
    d.line(f"s = @{{{F(s2,4)}}} = {F(s,4)} м.",indent=10)
    d.para(f"Шаг 4. По таблице Стьюдента для γ = 0,95 и n = {n} (k = {n-1}) находим tγ = 2,08.",indent=4,hang=5)
    sq_n=round(math.sqrt(n),4); prod=2.08*s; eps=round(prod/sq_n,3)
    d.para("Шаг 5. Точность оценки ε = tγ·s/@{n}:",indent=4,hang=5)
    d.line(f"ε = [[2,08 · {F(s,4)}||@{{22}}]]",indent=10)
    d.line(f"числитель: 2,08 · {F(s,4)} = {F(prod,5)};     знаменатель: @{{22}} = {F(sq_n,4)};",indent=10)
    d.line(f"ε = [[{F(prod,5)}||{F(sq_n,4)}]] = {F(eps,3)} м.",indent=10)
    lo=round(xb-eps,3); hi=round(xb+eps,3)
    d.para("Шаг 6. Границы интервала ~x − ε < a < ~x + ε:",indent=4,hang=5)
    d.line(f"нижняя граница: {F(xb,4)} − {F(eps,3)} = {F(lo,3)};",indent=10)
    d.line(f"верхняя граница: {F(xb,4)} + {F(eps,3)} = {F(hi,3)}.",indent=10)
    d.line(f"{F(lo,3)} < a < {F(hi,3)}.",indent=10)
    d.para(f"Ответ: оценка измеряемой величины ~x = {F(xb,3)} м; с надёжностью 0,95 a ∈ ({F(lo,3)} м; {F(hi,3)} м).")
