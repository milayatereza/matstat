def F(x,nd): return f"{x:.{nd}f}".replace(".",",").replace("-","−")
def table(d,header,rows,widths,fs=10):
    x0=LM+4*mm; xs_=[x0]
    for w in widths: xs_.append(xs_[-1]+w*mm)
    def row(r):
        d.need(2); y=d.y; top=y+ROW*0.72; bot=y-ROW*0.28; c=d.c; c.setLineWidth(.5)
        c.line(xs_[0],top,xs_[-1],top); c.line(xs_[0],bot,xs_[-1],bot)
        for xx in xs_: c.line(xx,top,xx,bot)
        for i,t in enumerate(r):
            w=lw(t,fs); draw_line(c,xs_[i]+(xs_[i+1]-xs_[i]-w)/2,y,t,fs)
        d.y-=ROW
    d.need(len(rows)+3); row(header)
    for r in rows: row(r)
    d.gap(.3)

def products(d,xs,ns,C,h,nd):
    n=sum(ns); us=[round((x-C)/h) for x in xs]
    assert all(abs((x-C)/h-u)<1e-9 for x,u in zip(xs,us))
    Su=sum(a*b for a,b in zip(ns,us)); Su2=sum(a*b*b for a,b in zip(ns,us)); Sc=sum(a*(b+1)**2 for a,b in zip(ns,us))
    rows=[[F(x,nd),str(a),str(u),str(a*u),str(a*u*u),str(a*(u+1)**2)] for x,a,u in zip(xs,ns,us)]
    rows.append(["Σ",str(n),"",str(Su),str(Su2),str(Sc)])
    table(d,["xᵢ","nᵢ","uᵢ","nᵢuᵢ","nᵢuᵢ²","nᵢ(uᵢ+1)²"],rows,[26,16,16,24,26,32])
    d.line("Контроль: Σnᵢ(uᵢ+1)² = Σnᵢuᵢ² + 2Σnᵢuᵢ + n:",indent=4)
    d.line(f"{Sc} = {Su2} + 2·({Su}) + {n} = {Su2+2*Su+n}  — контроль сошёлся." if Sc==Su2+2*Su+n else "ОШИБКА",indent=10)
    M1=Su/n; M2=Su2/n
    d.line("Условные моменты:",indent=4)
    d.line(f"M̄₁ = [[Σnᵢuᵢ||n]] = [[{Su}||{n}]] = {F(M1,4)};     M̄₂ = [[Σnᵢuᵢ²||n]] = [[{Su2}||{n}]] = {F(M2,4)}.",indent=10)
    xb=C+h*M1; D=h*h*(M2-M1**2); s2_=n/(n-1)*D
    d.line("Оценки:",indent=4)
    d.line(f"~x = M̄₁·Δ + C = {F(M1,4)}·{F(h,2) if h<1 else F(h,0)} + {F(C,nd)} = {F(xb,nd+2)};",indent=10)
    d.line(f"Dв = Δ²·(M̄₂ − M̄₁²) = {F(h*h,4 if h<1 else 0)}·({F(M2,4)} − {F(M1**2,4)}) = {F(D,6 if h<1 else 4)};",indent=10)
    p=6 if h<1 else 4
    d.line(f"σв = @{{Dв}} = {F(D**.5,5 if h<1 else 4)};",indent=10)
    d.line(f"s² = [[n||n − 1]]·Dв = [[{n}||{n-1}]]·{F(D,p)} = {F(s2_,p)};   s = @{{s²}} = {F(s2_**.5,5 if h<1 else 4)}.",indent=10)
    return n,xb,D,s2_

