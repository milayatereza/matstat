def task1(d):
    d.newpage(); d.head("Задача 1 (вариант 4). Скорости автомобиля ГАЗ-51"); d.gap(.2)
    d.para("Дано: 100 значений скорости (таблица в задании), от 25 до 41. Найти: ~x, Dв, σв (и s²) упрощённым методом (метод произведений) и прямым расчётом. Интервальный ряд заменить статистическим, взяв середины интервалов.")
    d.line("Решение.")
    d.line("Шаг 1. n = 100; xmin = 25; xmax = 41; размах 41 − 25 = 16.",indent=4)
    d.line("Число интервалов по Стерджессу: k = 1 + 3,31·lg 100 = 7,62 ≈ 8; Δ = 16/8 = 2.",indent=4)
    d.line("Интервалы [25; 27), [27; 29), …, [39; 41] (последний включает 41).",indent=4)
    h=2;lo=25;cnt=[0]*8
    for v in t1: cnt[min(int((v-lo)//h),7)]+=1
    mids=[lo+h*i+h/2 for i in range(8)]
    rows=[[f"{lo+h*i}–{lo+h*(i+1)}",F(mids[i],0),str(cnt[i])] for i in range(8)]
    rows.append(["Σ","",str(sum(cnt))])
    d.line("Шаг 2. Подсчёт частот nᵢ и середины интервалов xᵢ (это новые варианты):",indent=4)
    table(d,["интервал","xᵢ (середина)","nᵢ"],rows,[36,40,24])
    d.line("Шаг 3. Ложный нуль: наибольшая частота 29 у варианты 32, поэтому C = 32; Δ = 2;",indent=4)
    d.line("uᵢ = (xᵢ − 32)/2 = −3, −2, −1, 0, 1, 2, 3, 4.",indent=4)
    d.line("Шаг 4. Метод произведений — расчётная таблица:",indent=4)
    n,xb,D,s2_=products(d,mids,cnt,32,2,0)
    d.gap(.4)
    d.line("Прямой расчёт (по тому же ряду с серединами интервалов):",indent=0)
    xsum=sum(a*b for a,b in zip(mids,cnt))
    d.line(f"~x = [[Σnᵢxᵢ||n]] = [[{F(xsum,0)}||100]] = {F(xsum/100,2)}.",indent=10)
    rows=[[F(x,0),str(a),F(x-xb,2),F((x-xb)**2,4),F(a*(x-xb)**2,4)] for x,a in zip(mids,cnt)]
    tot=sum(a*(x-xb)**2 for x,a in zip(mids,cnt)); rows.append(["Σ","100","","",F(tot,4)])
    table(d,["xᵢ","nᵢ","xᵢ − ~x","(xᵢ − ~x)²","nᵢ(xᵢ − ~x)²"],rows,[18,14,28,34,38])
    d.line(f"Dв = [[Σnᵢ(xᵢ − ~x)²||n]] = [[{F(tot,4)}||100]] = {F(tot/100,4)};   σв = {F(math.sqrt(tot/100),4)};",indent=4)
    d.line(f"s² = [[100||99]]·{F(tot/100,4)} = {F(tot/99,4)}.",indent=4)
    d.line("Результаты обоих методов совпали.",indent=4)
    d.line("Ответ.",fs=FS+.5)
    d.para(f"~x = {F(xb,2)}; Dв = {F(D,4)}; σв = {F(D**.5,3)}; исправленные s² = {F(s2_,4)}, s = {F(s2_**.5,3)}. (Замечание: по несгруппированным 100 значениям ~x = 32,887, Dв = 9,2421 — небольшая разница из-за замены значений серединами интервалов.)",indent=4)

