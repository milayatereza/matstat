    d.para("Центральный эмпирический момент k-го порядка: mₖ = (1/n)·Σ nᵢ(xᵢ − ~x)ᵏ, где Σnᵢ = n, ~x = (1/n)·Σ nᵢxᵢ.")
    d.line("1) Нулевой порядок:",fs=FS+.5)
    d.line("m₀ = [[1||n]]·Σ nᵢ(xᵢ − ~x)⁰ = [[1||n]]·Σ nᵢ·1 = [[n||n]] = 1.",indent=6)
    d.line("2) Первый порядок:",fs=FS+.5)
    d.line("m₁ = [[1||n]]·Σ nᵢ(xᵢ − ~x) = [[1||n]]·Σ nᵢxᵢ − ~x·[[1||n]]·Σ nᵢ = ~x − ~x·1 = 0.",indent=6)
    d.line("(Сумма отклонений от среднего всегда равна нулю.)",indent=6)
    d.line("3) Второй порядок:",fs=FS+.5)
    d.line("m₂ = [[1||n]]·Σ nᵢ(xᵢ − ~x)² = Dв  (по определению выборочной дисперсии).",indent=6)
    d.para("Через обычные моменты: пусть dᵢ = xᵢ − C, тогда M₁′ = (1/n)·Σ nᵢdᵢ = ~x − C и xᵢ − ~x = dᵢ − M₁′:",indent=6)
    d.line("m₂ = [[1||n]]·Σ nᵢ(dᵢ − M₁′)² = [[1||n]]·Σ nᵢ(dᵢ² − 2dᵢM₁′ + (M₁′)²)",indent=6)
    d.line("= [[1||n]]·Σ nᵢdᵢ² − 2M₁′·[[1||n]]·Σ nᵢdᵢ + (M₁′)²·[[1||n]]·Σ nᵢ",indent=6)
    d.line("= M₂′ − 2M₁′·M₁′ + (M₁′)²·1 = M₂′ − (M₁′)².",indent=6)
    d.line("Через условные моменты (M′ₖ = Δᵏ·M̄ₖ):  Dв = Δ²·(M̄₂ − M̄₁²).",indent=6)
    d.line("Ответ: m₀ = 1; m₁ = 0; m₂ = Dв = M₂′ − (M₁′)² = Δ²(M̄₂ − M̄₁²).",fs=FS+.5)
